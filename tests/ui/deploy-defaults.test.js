import { readFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { describe, expect, it } from 'vitest';

describe('safe Firebase defaults', () => {
  it('a bare `firebase deploy` of the root config is refused by its predeploy guard', () => {
    const hosting = JSON.parse(readFileSync('firebase.json', 'utf8')).hosting;
    expect(hosting.predeploy).toEqual(['node scripts/refuse-default-hosting-deploy.cjs']);
    const run = spawnSync(process.execPath, ['scripts/refuse-default-hosting-deploy.cjs'], { encoding: 'utf8' });
    expect(run.status).toBe(1);
    expect(run.stderr).toContain('--config firebase.hosting.booking.json');
  });
  it('the default project is the live hilik-site; the old project stays reachable only by alias', () => {
    const projects = JSON.parse(readFileSync('.firebaserc', 'utf8')).projects;
    expect(projects.default).toBe('hilik-site');
    expect(projects.legacy).toBe('hilik-rosenberg-ddb9b');
    expect(JSON.parse(readFileSync('firebase.hosting.booking.json', 'utf8')).hosting.site).toBe('hilik-site');
  });
  it('stale sitemaps and the unused hero image are gone; the sitemap is generated by the build', () => {
    for (const file of ['sitemap.xml', 'public/sitemap.xml', 'src/assets/hero-bg.jpeg']) expect(existsSync(file)).toBe(false);
    expect(readFileSync('index.html', 'utf8')).not.toMatch(/בכל חמישי|רשת 13|fonts\.googleapis/);
  });
});
